export function getCompanyBySlug(slug: string): CompanyData | undefined {
  if (!slug) return undefined;
  const clean = slug.toLowerCase().trim();
  return TOP_100_COMPANIES.find(
    (c) =>
      c.slug.toLowerCase() === clean ||
      c.id.toLowerCase() === clean ||
      c.ticker.toLowerCase() === clean
  );
}

export function searchCompanies(query: string, sector: string = "all"): CompanyData[] {
  const q = query.toLowerCase().trim();
  return TOP_100_COMPANIES.filter((company) => {
    const matchesSector = sector === "all" || company.sector.toLowerCase() === sector.toLowerCase();
    const matchesQuery =
      !q ||
      company.name.toLowerCase().includes(q) ||
      company.shortName.toLowerCase().includes(q) ||
      company.ticker.toLowerCase().includes(q) ||
      company.ceo.toLowerCase().includes(q) ||
      company.country.toLowerCase().includes(q) ||
      company.sector.toLowerCase().includes(q);
    return matchesSector && matchesQuery;
  });
}
